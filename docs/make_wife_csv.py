def replace_token(text: str, src: str, dst: str) -> str:
    if " " in src or any(ch in src for ch in "→`[]"):
        return text.replace(src, dst)
    return re.sub(
        r"(?<![A-Za-zА-Яа-яІіЇїЄєҐґ0-9])" + re.escape(src) + r"(?![A-Za-zА-Яа-яІіЇїЄєҐґ0-9])",
        dst,
        text,
    )


