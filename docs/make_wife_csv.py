def longest_first(pairs):
    return sorted(pairs, key=lambda x: len(x[0]), reverse=True)


SECTION_MAP_SORTED = longest_first(SECTION_MAP)
WHERE_SORTED = longest_first(WHERE_BY_PREFIX)


def friendly_section(raw: str) -> str:
    for prefix, name in SECTION_MAP_SORTED:
        if raw.startswith(prefix):
            return name
    return raw


def where_for(section: str, ident: str) -> str:
    for prefix, where in WHERE_SORTED:
        if section.startswith(prefix):
            return where
    if ident.startswith("X"):
        return "Нижня кнопка «Bity AI», поле внизу чату"
    return "Відкрий додаток"


def polish(text: str) -> str:
    for a, b in POST_FIXES:
        text = text.replace(a, b)
    text = re.sub(r"[^\S\n]+", " ", text)
    text = text.replace(" .", ".").replace(" ,", ",")
    text = re.sub(r" *\n *", "\n", text).strip()
    return text


def humanize(text: str) -> str:
    if not text:
        return text
    text = text.replace("`", "")
    for a, b in longest_first(REPLACEMENTS):
        text = replace_token(text, a, b)
    for a, b in longest_first(WORD_LEFTOVERS):
        text = replace_token(text, a, b)
    text = polish(text)
    text = text.replace(" → ", " потім ").replace("→", " потім ")
    return polish(text)


def quotes_to_write(text: str) -> str:
    parts = re.findall(r"`([^`]+)`", text)
    if not parts:
        return ""
    lines = [f"«{p.strip()}»" for p in parts if p.strip() and len(p.strip()) > 1]
    if not lines:
        return ""
    if len(lines) == 1:
        return f"Напиши в поле рівно так і надішли:\n{lines[0]}"
    numbered = "\n".join(f"{i + 1}) {line}" for i, line in enumerate(lines))
    return f"Напиши по черзі (після кожної — надішли і дочекайся відповіді):\n{numbered}"


def start_verb(text: str) -> str:
    for a, b in VERB_START:
        if text.startswith(a):
            return b + text[len(a) :]
    return text


def action_text(raw_steps: str, ident: str, title: str, section: str) -> str:
    quoted = quotes_to_write(raw_steps)
    steps = humanize(raw_steps)
    title_h = humanize(title)
    if quoted and (ident.startswith(("X", "AA", "Z")) or "Smoke" in section):
        extra = steps
        for q in re.findall(r"`([^`]+)`", raw_steps):
            extra = extra.replace(q, "").replace("«»", "")
        extra = extra.strip(" .;")
        if extra and len(extra) > 20 and "Напиши" not in extra[:20]:
            return f"{quoted}\n({start_verb(extra)})"
        return quoted
    if not steps:
        return f"Зроби так: {title_h}."
    steps = start_verb(steps)
    if steps and steps[0].islower():
        steps = steps[0].upper() + steps[1:]
    if not steps.endswith("."):
        steps += "."
    return polish(steps)


def result_text(raw: str) -> str:
    t = humanize(raw)
    if not t:
        return "Екран виглядає нормально. Додаток не вилетів і не зависає."
    t = t[0].upper() + t[1:]
    return polish(t)


